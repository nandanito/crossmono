"""Make the CrossMono boot and sleep logo and the web UI favicon from src/mono/images/logo.svg (ADR 0007).

    python3 scripts/mono/make_logo.py

Writes src/mono/images/MonoLogo120.h (120x120, 1 bit per pixel) and copies the SVG to the web UI favicon,
src/network/html/assets/crosspoint-icon.svg (upstream's path, our content). Needs cairosvg and Pillow from
scripts/requirements.txt; on macOS with Homebrew's cairo, set DYLD_FALLBACK_LIBRARY_PATH=/opt/homebrew/lib.
Commit all three files.
"""

import argparse
import io
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
SVG = ROOT / "src" / "mono" / "images" / "logo.svg"
HEADER = ROOT / "src" / "mono" / "images" / "MonoLogo120.h"
FAVICON = ROOT / "src" / "network" / "html" / "assets" / "crosspoint-icon.svg"
NAME = "MonoLogo120"
SIZE = 120
THRESHOLD = 128  # grey level from which a pixel is white
BYTES_PER_LINE = 19  # what clang-format keeps at 120 columns, so a rerun gives no format diff


def rasterize(svg: bytes, size: int) -> list[list[int]]:
    """Render the SVG at size x size on white; rows of grey levels 0-255."""
    import cairosvg
    from PIL import Image

    png = cairosvg.svg2png(bytestring=svg, output_width=size, output_height=size)
    image = Image.open(io.BytesIO(png)).convert("RGBA")
    white = Image.new("RGBA", image.size, (255, 255, 255, 255))
    white.alpha_composite(image)
    grey = white.convert("L").tobytes()
    return [list(grey[y * size : (y + 1) * size]) for y in range(size)]


def to_panel(rows: list[list[int]]) -> list[list[int]]:
    """Rotate 90 degrees counter-clockwise.

    GfxRenderer::drawImage copies the bytes to the panel without rotating them, and the UI's Portrait orientation
    turns the panel 90 degrees clockwise, so the image is stored turned the other way (as Logo120.h is)."""
    width = len(rows[0])
    return [[row[width - 1 - y] for row in rows] for y in range(width)]


def pack(rows: list[list[int]]) -> bytes:
    """Rows of grey levels to the drawImage format: row by row, 8 pixels a byte, first pixel in the high bit,
    1 = white, 0 = black."""
    width = len(rows[0])
    if width % 8 or any(len(row) != width for row in rows):
        raise ValueError(f"rows must all be the same width, a multiple of 8 (got {sorted({len(r) for r in rows})})")
    out = bytearray()
    for row in rows:
        for x in range(0, width, 8):
            byte = 0
            for bit, level in enumerate(row[x : x + 8]):
                if level >= THRESHOLD:
                    byte |= 0x80 >> bit
            out.append(byte)
    return bytes(out)


def header(name: str, data: bytes, width: int, height: int) -> str:
    lines = [
        ", ".join(f"0x{b:02x}" for b in data[i : i + BYTES_PER_LINE]) for i in range(0, len(data), BYTES_PER_LINE)
    ]
    body = ",\n    ".join(lines)
    return (
        "#pragma once\n"
        "#include <cstdint>\n"
        "\n"
        "// Generated by scripts/mono/make_logo.py from logo.svg; do not edit.\n"
        f"// {width}x{height}, 1 bit per pixel, stored rotated for GfxRenderer::drawImage.\n"
        f"inline constexpr uint8_t {name}[] = {{\n"
        f"    {body}}};\n"
    )


def parse_header(text: str) -> tuple[str, int, int, bytes]:
    """The array name, size and bytes of a header written by header()."""
    size = re.search(r"^// (\d+)x(\d+), 1 bit per pixel", text, re.MULTILINE)
    array = re.search(r"uint8_t (\w+)\[\] = \{(.*?)\};", text, re.DOTALL)
    if not size or not array:
        raise ValueError("not a make_logo.py header")
    data = bytes(int(value, 16) for value in re.findall(r"0x([0-9a-fA-F]{2})", array.group(2)))
    return array.group(1), int(size.group(1)), int(size.group(2)), data


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--svg", type=Path, default=SVG)
    parser.add_argument("--header", type=Path, default=HEADER)
    parser.add_argument("--favicon", type=Path, default=FAVICON)
    args = parser.parse_args(argv)

    svg = args.svg.read_bytes()
    data = pack(to_panel(rasterize(svg, SIZE)))
    args.header.write_text(header(NAME, data, SIZE, SIZE), encoding="utf-8")
    args.favicon.write_bytes(svg)
    print(f"Wrote {args.header} ({len(data)} bytes) and {args.favicon}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
